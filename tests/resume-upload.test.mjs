import {strict as assert} from 'node:assert';
import ts from 'typescript';
import {readFileSync} from 'node:fs';
const js=ts.transpileModule(readFileSync('lib/resume.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {validateResume,safeResumeName,resumeContentType,MAX_RESUME_BYTES}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const bytes=s=>new TextEncoder().encode(s);
assert.equal(validateResume('cv.pdf',bytes('%PDF-1.4\nexample')),null);
assert.equal(validateResume('CV.PDF',bytes('%PDF-1.7')),null);
assert.equal(validateResume('cv.pdf',new Uint8Array()),'Attach your résumé before submitting.');
assert.equal(validateResume('cv.pdf',bytes('<html>not a pdf</html>')),'Please upload a valid PDF file.');
assert.equal(validateResume('cv.exe',bytes('%PDF-1.4')),'Accepted formats: PDF or DOCX.');
assert.equal(validateResume('cv.docx',bytes('PK\u0003\u0004[Content_Types].xml word/document.xml')),null);
assert.equal(validateResume('cv.docx',bytes('PK\u0003\u0004ordinary.zip')),'Please upload a valid DOCX résumé.');
assert.equal(validateResume('cv.pdf',new Uint8Array(MAX_RESUME_BYTES+1)),'The résumé must be 5 MB or smaller.');
assert.equal(safeResumeName('bad\r\n"file.pdf').includes('\r'),false);
assert.equal(safeResumeName('bad\r\n"file.pdf').includes('"'),false);
assert.equal(resumeContentType('cv.pdf'),'application/pdf');
assert.match(resumeContentType('cv.docx'),/wordprocessingml/);
console.log('12 résumé validation checks passed.');
